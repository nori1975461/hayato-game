  const t = ang * Math.PI / 180, ux = Math.sin(t), uy = -Math.cos(t), nx = -uy, ny = ux, ls = litSign(nx, ny), neck = hw * 0.36;
  const PROF = [[0, 1.13], [0.1, 1.05], [0.45, 0.7], [0.78, 0.86], [0.86, 0.9], [1.0, 0.32]];                                 // 裾 → 腰のくびれ → 胸 → なで肩 → 首の付け根
