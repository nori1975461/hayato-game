// ⑩ 後の腕（wingR/wingL・深度7＝円光の後ろを通って高く掲げる）
//   右 23×34：肩 (2,31)＝世界 (10,-16)。肘 (21,19)＝(29,-28) → 手首 (16,9) → 拳 (15,7) が **日輪**（金の円盤）を掲げる
//   左 24×35：肩 (21,32)＝世界 (-10,-16)。肘 (2,20)＝(-29,-28) → 手首 (7,10) → 拳 (8,7) が **欠けた月**（蒼硝子の三日月）を掲げる
// =====================================================================
const dimBone = (G) => { for (const row of G) for (let x = 0; x < row.length; x++) row[x] = { s: 'f', f: 'm', m: 'j', j: 'j' }[row[x]] || row[x]; };   // 後ろの腕は影に沈める（目障りにしない）
const WINGR_W = 23, WINGR_H = 34;
const WING_R = (() => {
  const G = g(WINGR_W, WINGR_H);
  arm(G, [[2, 31], [21, 19], [16, 9]], 3.2, 2.4); fist(G, 15, 7.5, 3.0, 2.6); dimBone(G);
  DISC(G, 15, 3.6, 3.6, 'k'); SPHERE(G, 15, 3.6, 3.1, ['y', 'Y', 'G', 'G', 'W'], [-0.5, -0.62, 0.6], 0.12);   // 日輪
  OUTLINE(G);
  return R(G);
})();
const WINGL_W = 24, WINGL_H = 35;
const WING_L = (() => {
  const G = g(WINGL_W, WINGL_H);
  arm(G, [[21, 32], [2, 20], [7, 10]], 3.2, 2.4); fist(G, 8, 7.5, 3.0, 2.6); rustSpeck(G, 2, 22, 10, 33, 6); dimBone(G);
  DISC(G, 8, 4, 3.6, 'k'); DISC(G, 8, 4, 3.0, 'N'); DISC(G, 8, 4, 2.2, 'P');                          // 欠けた月＝三日月に切り欠き
  DISC(G, 9.6, 3.2, 2.7, '.'); ARC(G, 9.6, 3.2, 2.7, 2.7, 120, 250, 'k');
  for (let a = 200; a <= 240; a += 3) AT(G, 8, 4, 3.0, 3.0, a, 'k'); P(G, 5.6, 2.8, 'd');
  OUTLINE(G);
  return R(G);
})();

