// 花弁：根元 (bx,by) → 先端 (tx,ty)。蒼硝子＝地 Q・影側 q・光側の一筋 P・光側の縁 N・影側の縁 k・先端 C・中肋は骨。gilt＝縁と先端を金。withered＝枯れ
