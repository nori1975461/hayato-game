//   右 29×41：肩 (2,32)＝世界 (14,-12)。肘 (17,36)＝(29,-8) → 手首 (16,26) → 拳 (15,22) が **曲刀** を上へ掲げる（鍔は金・刃は骨の白）
//   左 29×27：肩 (26,17)＝世界 (-14,-12)。肘 (11,21)＝(-29,-8) → 手首 (12,11) → 拳 (13,7) が **傾いた盃** を持ち、縁から深紅が垂れる
// =====================================================================
const BASER_W = 35, BASER_H = 41;
const BASE_R = (() => {   // 肩 (2,30)＝世界 (14,-12)。肘 (18,34)＝(30,-8) → 手首 (21,24) → 拳 (22,21)＝(34,-21) が曲刀を外上へ掲げる（金棒と重ねない）
  const G = g(BASER_W, BASER_H);
  arm(G, [[2, 30], [18, 34], [21, 24]], 3.2, 2.4);
  const bx0 = 22, by0 = 18.5, bx1 = 33, by1 = 1, dx = bx1 - bx0, dy = by1 - by0, L = Math.hypot(dx, dy), ux = dx / L, uy = dy / L, nx = -uy, ny = ux;   // 曲刀
  for (let u = 0; u <= 1; u += 0.004) {
    const w = 2.6 * (1 - u * 0.7), cx = bx0 + ux * L * u + nx * 1.8 * u * u, cy = by0 + uy * L * u + ny * 1.8 * u * u;
    for (let k = -w; k <= w; k += 0.25) P(G, cx + nx * k, cy + ny * k, k > w * 0.35 ? (u > 0.93 ? 'n' : 's') : k > -w * 0.3 ? 'f' : k > -w * 0.75 ? 'm' : 'j');
  }
  for (let k = -3.5; k <= 3.5; k += 0.25) { P(G, bx0 + nx * k, by0 + ny * k + 0.5, 'Y'); P(G, bx0 + nx * k, by0 + ny * k + 1.5, 'y'); }   // 鍔
  fist(G, 22, 21.5, 3.2, 3.0);
  OUTLINE(G);
  return R(G);
})();
const BASEL_W = 29, BASEL_H = 27;
const BASE_L = (() => {
  const G = g(BASEL_W, BASEL_H);
  arm(G, [[26, 17], [11, 21], [12, 11]], 3.2, 2.4);
  for (let y = -2.6; y <= 2.6; y += 0.25) for (let x = -3.4; x <= 3.4; x += 0.25) {                   // 盃（金・左へ傾く）
    const rx = x * 0.94 + y * 0.34, ry = -x * 0.34 + y * 0.94;
    if ((rx / 3.4) ** 2 + (ry / 2.6) ** 2 > 1 || ry < -1.2) continue;
    P(G, 9.5 + x, 4.5 + y, rx < -1 ? 'W' : rx < 1.2 ? 'G' : 'Y');
  }
  for (let x = 6.5; x <= 12.5; x += 0.25) P(G, x, 2.3 + (x - 6.5) * -0.36 + 1.6, 'k');               // 盃の縁
  for (let x = 7; x <= 11.5; x += 0.25) P(G, x, 3.2 + (x - 7) * -0.36 + 1.2, x < 8.5 ? 'R' : 'r');   // 深紅の酒
  for (let y = 4; y <= 21; y += 0.25) P(G, 6.2 - (y - 4) * 0.04, y, y < 6 ? 'A' : y % 3 < 1.5 ? 'R' : 'r');   // 縁から垂れて落ちる深紅
  P(G, 5.4, 22.5, 'R'); P(G, 6.4, 24, 'r'); P(G, 5.8, 26, 'R');
  fist(G, 13, 8, 3.2, 3.0);
  rustSpeck(G, 8, 27, 8, 22, 6);
  OUTLINE(G);
  return R(G);
})();

