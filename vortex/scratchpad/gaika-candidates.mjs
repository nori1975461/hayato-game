const LIGHT = [-0.5, -0.62];   // 光は左上（他の三体と同じ）
const litSign = (nx, ny) => (LIGHT[0] * nx + LIGHT[1] * ny > 0 ? 1 : -1);
const shade4 = (v) => (v > 0.45 ? 's' : v > -0.05 ? 'f' : v > -0.5 ? 'm' : 'j');

